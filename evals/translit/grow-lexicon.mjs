// grow-lexicon.mjs — writes server/voice/translit/lexicon-learned.js from the DEV split of the gold ONLY (the test split
// is never read here, so run.mjs's test numbers are held-out). For each lowercase Roman word:
//   Hindi in >= 90% of its dev occurrences  → LEARNED_HI (most frequent Devanagari spelling; spoken forms preferred)
//   keep in  >= 90%                         → LEARNED_KEEP (blocks the rule fallback from touching it)
//   anything in between                     → LEARNED_AMBIG (resolved by sentence context in index.js)
//   node evals/translit/grow-lexicon.mjs
import fs from "node:fs";
import path from "node:path";
import { words } from "./tokens.mjs";
const HERE = path.dirname(new URL(import.meta.url).pathname);
const ROOT = path.resolve(HERE, "../..");
const corpus = JSON.parse(fs.readFileSync(path.join(HERE, "data/corpus.json"), "utf8"));
const gold = JSON.parse(fs.readFileSync(path.join(HERE, "data/gold.json"), "utf8")).rows;
const SPOKEN = { "वह": "वो", "यह": "ये", "वे": "वो" };
const stat = new Map();
for (const r of corpus.rows) {
  const g = gold[r.id]; if (!g || g.split !== "dev") continue;
  words(r.text).forEach((x, k) => {
    const w = x.w.toLowerCase().replace(/’/g, "'"); const l = g.labels[k]; if (l == null) return;
    const s = stat.get(w) ?? { n: 0, keep: 0, hi: new Map() }; s.n++;
    if (l === "=") s.keep++; else { const d = SPOKEN[l] ?? l; s.hi.set(d, (s.hi.get(d) ?? 0) + 1); }
    stat.set(w, s);
  });
}
const HI = {}, KEEP = [], AMBIG = {};
for (const [w, s] of [...stat].sort((a, b) => a[0].localeCompare(b[0]))) {
  const hiN = s.n - s.keep;
  const best = [...s.hi].sort((a, b) => b[1] - a[1])[0]?.[0];
  if (hiN / s.n >= 0.9) HI[w] = best;
  else if (s.keep / s.n >= 0.9) KEEP.push(w);
  else AMBIG[w] = { deva: best, pHindi: +(hiN / s.n).toFixed(2), n: s.n };
}
const out = `// GENERATED by evals/translit/grow-lexicon.mjs from the DEV split of evals/translit/data/gold.json (${new Date().toISOString().slice(0, 10)}).
// Do not edit by hand: add hand entries to lexicon.js (which wins over this file) and re-run the generator.
// ${Object.keys(HI).length} Hindi words, ${KEEP.length} keep-Latin words, ${Object.keys(AMBIG).length} context-ambiguous words.
export const LEARNED_HI = Object.freeze(${JSON.stringify(HI)});
export const LEARNED_KEEP = Object.freeze(new Set(${JSON.stringify(KEEP)}));
export const LEARNED_AMBIG = Object.freeze(${JSON.stringify(AMBIG)});
`;
fs.writeFileSync(path.join(ROOT, "server/voice/translit/lexicon-learned.js"), out);
console.log("HI", Object.keys(HI).length, "KEEP", KEEP.length, "AMBIG", Object.keys(AMBIG).length);
console.log("AMBIG:", JSON.stringify(AMBIG));
