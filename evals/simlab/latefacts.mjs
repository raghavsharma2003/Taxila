// Late boards the child never saw (main, 2026-10-21): before runner.mjs followed the Studio wire, the child's screen was the
// turn's ui.studioSlot alone, so a slot that came back "planning" read "nothing drawn yet" even when the board's script
// landed on /api/studio/stream a second later (the phone showed it). The judge always had the board (boardPages); only the
// child did not. This finds those turns in old records, by time: turn n's slot is planning with nothing drawn and a
// board_page was created after its reply (−500 ms) and before turn n+1 was sent. Records made with the wire (rec.wire set,
// not "off") are skipped: their screen already followed the wire.
//   harnessAffected — the child's NEXT line says nothing is on screen / no drawing (her words then are the harness's, not
//                     the product's: never cite them as a product failure)
//   node evals/simlab/latefacts.mjs [results-dir]   → <results-dir>/LATE-BOARDS.json + LATE-BOARDS.md (per-run table)
import { readdirSync, readFileSync, existsSync, writeFileSync } from "fs";
import { join } from "path";

const root = process.argv[2] ?? new URL("./results", import.meta.url).pathname;
// "nothing on screen" in the child's words (Hinglish / Hindi / English)
const NOTHING = /(kuch|kuchh|koi)\s*(bhi\s*)?(nahi|nahin|nhi)\s*(dikh|aa\s*raha|hai\s*screen|screen)|screen\s*(pe|par|mein)\s*(kuch|kuchh)\s*(bhi\s*)?(nahi|nahin|nhi)|(nahi|nahin|nhi)\s*dikh(\s*rah[aie]|a\b|i\b|ai\b|aya|ayi|ayaa)|(drawing|picture|tasveer|photo|board)\s*(to|toh)?\s*(nahi|nahin|nhi)|(dikhaya|dikhayi|dikha)\s*(hi\s*)?(nahi|nahin|nhi)|कुछ\s*(भी\s*)?नहीं\s*(दिख|है)|नहीं\s*दिख|(nothing|can't see|cannot see|don't see|no picture|no drawing|where is the (picture|drawing|board))/i;

const runs = [], affected = [];
const tot = { runs: 0, lessons: 0, lessonsWithPages: 0, planningTurns: 0, boardLandedUnseen: 0, lessonsHit: 0, harnessAffected: 0 };
for (const run of readdirSync(root).sort()) {
  const d = join(root, run, "records");
  if (!existsSync(d)) continue;
  const row = { run, lessons: 0, lessonsWithPages: 0, wired: 0, planningTurns: 0, boardLandedUnseen: 0, lessonsHit: 0, harnessAffected: 0 };
  for (const f of readdirSync(d).filter((f) => f.endsWith(".json")).sort()) {
    let r;
    try { r = JSON.parse(readFileSync(join(d, f), "utf8")); } catch { continue; }
    row.lessons++;
    if (r.wire && r.wire !== "off") { row.wired++; continue; }
    if (r.boardPages) row.lessonsWithPages++;
    const pages = (r.boardPages ?? []).map((p) => Date.parse(p.at));
    const T = (r.turns ?? []).filter((t) => t.at);
    let hit = 0;
    for (let i = 0; i < T.length; i++) {
      const t = T[i], sl = t.ui?.studioSlot;
      if (!sl || sl.kind || !/planning/.test(sl.state ?? "")) continue;
      row.planningTurns++;
      const from = Date.parse(t.at), nx = T[i + 1], to = nx ? Date.parse(nx.at) - (nx.ms ?? 0) : from + 60_000;
      if (!pages.some((x) => x > from - 500 && x < to)) continue;
      row.boardLandedUnseen++; hit++;
      const said = nx ? String(nx.child?.chipLabel ?? nx.child?.say ?? "") : "";
      const flag = !!nx && NOTHING.test(said);
      if (flag) row.harnessAffected++;
      affected.push({ run, persona: r.persona, arm: r.arm, lane: r.lane, lessonId: r.lessonId ?? null, turn: t.n, nextTurn: nx?.n ?? null, harnessAffected: flag, ...(flag ? { childSaid: said.slice(0, 160) } : {}) });
    }
    if (hit) row.lessonsHit++;
  }
  if (!row.lessons) continue;
  runs.push(row);
  tot.runs++;
  for (const k of ["lessons", "lessonsWithPages", "planningTurns", "boardLandedUnseen", "lessonsHit", "harnessAffected"]) tot[k] += row[k];
}

writeFileSync(join(root, "LATE-BOARDS.json"), JSON.stringify({ method: "turn n slot planning with nothing drawn; a board_page created in (reply n − 500 ms, send n+1); harnessAffected = the child's next line says nothing is on screen", at: new Date().toISOString(), total: tot, runs, turns: affected }, null, 1));
const md = [
  "# Late boards the child never saw (harness, before 2026-10-21)",
  "",
  "Before `runner.mjs` followed the Studio wire, the simulated child saw only the turn's `ui.studioSlot`. A slot that came back",
  "`planning` read \"nothing drawn yet\" even when the board's script reached the phone a second later. The judge always had the",
  "board (boardPages); only the child did not. **harnessAffected** turns: the child's next line says nothing is on screen. Those",
  "words are the harness's, not the product's: never cite them as a product failure. Per-turn list: `LATE-BOARDS.json`.",
  "",
  `Method: turn n's slot is planning with nothing drawn and a board_page was created after its reply (−500 ms) and before turn n+1 was sent. Generated by \`node evals/simlab/latefacts.mjs\` on ${new Date().toISOString().slice(0, 10)}. Records made with the wire are skipped.`,
  "",
  "| run | lessons | with board pages | planning turns | board landed unseen | lessons hit | harness-affected child lines |",
  "|---|---|---|---|---|---|---|",
  ...runs.filter((r) => r.lessons > r.wired).map((r) => `| ${r.run} | ${r.lessons} | ${r.lessonsWithPages} | ${r.planningTurns} | ${r.boardLandedUnseen} | ${r.lessonsHit} | ${r.harnessAffected} |`),
  `| **total (${tot.runs} runs)** | ${tot.lessons} | ${tot.lessonsWithPages} | ${tot.planningTurns} | ${tot.boardLandedUnseen} | ${tot.lessonsHit} | ${tot.harnessAffected} |`,
  "",
].join("\n");
writeFileSync(join(root, "LATE-BOARDS.md"), md);
console.log(`late boards: ${tot.boardLandedUnseen} turns in ${tot.lessonsHit} of ${tot.lessonsWithPages} lessons with pages (${tot.runs} runs); harness-affected child lines: ${tot.harnessAffected}`);
