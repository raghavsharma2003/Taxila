// Prepare the HELD-OUT battery run on the SAME harness as evals/conversation-v2 (run.mjs + judge.mjs + rubric.mjs,
// byte for byte): copies them into evals/conversation-r2-heldout-run/ (generated; not tracked), with a cases.mjs that re-exports heldout-cases.mjs,
// and writes the run's prescreen.json from the safety predicate (scanSafety) — a held-out line the predicate reads as
// distress is never sent (none is meant to be). Then:
//
//   node evals/conversation-r2/prep-heldout.mjs --out <dir>
//   NODE_USE_ENV_PROXY=1 node --env-file=.env.local evals/conversation-r2-heldout-run/run.mjs --out <dir> --base <url> --concurrency 4
//   NODE_USE_ENV_PROXY=1 node --env-file=.env.local evals/conversation-r2-heldout-run/judge.mjs --dir <dir>
//   node docs/design/ship5/p5-interaction/battery/score.mjs <dir>
import fs from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const argv = process.argv.slice(2);
const OUT = argv[argv.indexOf("--out") + 1];
if (!OUT || argv.indexOf("--out") < 0) { console.error("--out <dir> required"); process.exit(2); }
// a sibling of evals/conversation-v2 (run.mjs and judge.mjs resolve the repo root as two levels up from their own dir)
const RUN = join(ROOT, "evals", "conversation-r2-heldout-run");
fs.mkdirSync(RUN, { recursive: true });
for (const f of ["run.mjs", "judge.mjs", "rubric.mjs", "topics.mjs"]) fs.copyFileSync(join(ROOT, "evals", "conversation-v2", f), join(RUN, f));
fs.writeFileSync(join(RUN, "cases.mjs"), "// generated by prep-heldout.mjs: the held-out cases on the conversation-v2 harness\nexport { CASES, FAMILY } from \"../conversation-r2/heldout-cases.mjs\";\n");
const { CASES } = await import("./heldout-cases.mjs");
const { scanSafety } = await import(join(ROOT, "server", "director", "safety.js"));
const rows = CASES.map((c) => ({ id: c.id, intent: c.intent, texts: [...(c.setup ?? []), c.text], distress: [...(c.setup ?? []), c.text].some((t) => scanSafety(t).distress), perTurn: [] }));
fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(join(OUT, "prescreen.json"), JSON.stringify({ source: "scanSafety (round 2 held-out)", rows }, null, 1));
console.log(`${CASES.length} held-out cases; ${rows.filter((r) => r.distress).length} withheld by the predicate; prescreen → ${join(OUT, "prescreen.json")}`);
