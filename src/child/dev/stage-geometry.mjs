// Writes docs/design/round7/app/STAGE-GEOMETRY.md and the box-contract proposal (stage-boxes.json) from stageLayout.ts,
// so the spec Studio applies is the solver the app runs, never a hand copy.
//   node src/child/dev/stage-geometry.mjs [--check]
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { solveStage, STAGE } from "../../ui-v3/kaksha/lesson/stageLayout.ts";

const OUT = new URL("../../../docs/design/round7/app/", import.meta.url);
const VIEWPORTS = [["p360", 360, 800], ["p412", 412, 915], ["w1280", 1280, 800], ["l1366", 1366, 768]];
const PAD = 232; // the Older NumberPad at full target size (4 rows of 52 + gaps), the tallest answer surface

const r = (x) => `${x.w}×${x.h} @ (${x.x}, ${x.y})`;
const rows = [];
const shrinks = [];
const boxes = {};
for (const family of ["older", "young"]) {
  boxes[family] = {};
  for (const [id, w, h] of VIEWPORTS) {
    const full = solveStage({ width: w, height: h, family, chips: family === "older", artifact: true });
    const withPad = solveStage({ width: w, height: h, family, chips: family === "older", artifact: true, answerNeed: PAD });
    const play = solveStage({ width: w, height: h, family, chips: family === "older", artifact: true, play: true });
    boxes[family][id] = {
      viewport: { w, h }, kind: full.kind,
      stage: { box: { w: full.slot.w, h: full.slot.h }, at: { x: full.slot.x, y: full.slot.y } },
      play: { box: { w: play.slot.w, h: play.slot.h }, at: { x: play.slot.x, y: play.slot.y } },
      stageWithAnswer: { box: { w: withPad.slot.w, h: withPad.slot.h }, at: { x: withPad.slot.x, y: withPad.slot.y } },
      pipZone: full.pip ? { w: full.pip.w, h: full.pip.h, inset: STAGE.pipInset, corner: "bottom-right" } : null,
      rail: { h: full.rail.h },
    };
    rows.push(`| ${family} | ${id} ${w}×${h} | ${full.kind} | ${r(full.slot)} | ${r(withPad.slot)} | ${full.pip ? `${full.pip.w}×${full.pip.h}` : "tile " + `${full.tile.w}×${full.tile.h}`} | ${full.rail.h} | ${full.chips ? full.chips.h : 0} | ${full.dock.h} | ${(full.stageShare * 100).toFixed(0)}% |`);
  }
}

const md = `# Stage-first lesson geometry (r7 stream E, app-lesson-stage-first)

Generated by \`node src/child/dev/stage-geometry.mjs\` from \`src/ui-v3/kaksha/lesson/stageLayout.ts\`; do not edit by hand.

**Decision.** D7 (main loop, 2026-11-04): content is the hero and her face is a PiP. This **supersedes PRODUCT-DESIGN-V2 §6.3.4**
("the face is never a PiP over content"; the four-zone Desk). The Desk's controller, sheets, safety floor, Summary/Debrief and
trouble screens are unchanged; only the lesson body is laid out stage-first (Kaksha skin). \`?ui=classic\` keeps the V2 Desk.

## Zones

- **phone** (portrait, and any width < ${STAGE.wideMinWidth}): top bar ${STAGE.top} · stage (slot + HUD rail ${STAGE.rail}) · answer surface (tiles / pad, only while up) · steer chips ${STAGE.chips} · dock ${STAGE.dock.older} (Young ${STAGE.dock.young}) · pad ${STAGE.pad}. Gutters ${STAGE.gutterPhone}.
- **wide** (≥ ${STAGE.wideMinWidth} wide, landscape, ≥ ${STAGE.landscapeMaxHeight} tall): top ${STAGE.topWide}; the stage column on the left; the side column (${STAGE.sideMin}-${STAGE.sideMax} px, ${STAGE.sideShare * 100}% of width): her tile, the caption, the answer surface (when it fits; her tile yields to 200 first), chips, dock ${STAGE.dockWide}. Gutters ${STAGE.gutterWide}.
- **landscape** (a phone turned, < ${STAGE.landscapeMaxHeight} tall): the wide grid without her tile; she is the PiP again.

## The slot (what Studio, games and modules draw into)

- One letterboxed slot. Pieces declare a design canvas (square 1000×1000, board 1000×760, wide 1000×625, cinema 1600×900) and fit with xMidYMid meet; letterbox bands take the stage background; nothing scrolls inside the slot.
- **PiP keep-clear zone:** the bottom-right square of side ${STAGE.pipShare * 100}% of the slot's short side (clamped ${STAGE.pipMin}-${STAGE.pipMax} px), inset ${STAGE.pipInset} px. Pieces put no label, value or target there on phones and short landscape. On wide screens there is no PiP (she is a tile in the side column), but keeping the zone clear costs nothing and lets one certified layout serve both.
- **Label zone:** top-left 18% × 12% stays clear for the stage tag; the top-right corner stays the piece's own (its corner controls). The Later pill sits bottom-left.
- **The HUD rail** sits under the slot, not over it: the question (or a game's goal rail in play mode) never covers the piece.
- **With nothing on the stage** the stage holds her (a large comms window with the caption), so it is never empty and no build state is shown. The PiP appears only while a piece holds the slot.
- **With an answer surface up** (tiles, the NumberPad), the piece stays on the stage in the smaller "with answer" box (phones). On wide screens the answer surface goes to the side column and the stage keeps its full box.

## Numbers

| family | viewport | kind | slot (artifact box) | slot with pad up | her face | rail | chips | dock | stage share |
|---|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## Against the certified box contract (server/forge3/certs/box-contract.json, "grow a box, never shrink one")

| family | viewport | certified tray box | stage slot (new) | certified play box | play slot (new) | grows |
|---|---|---|---|---|---|---|
${(() => {
  let contract = null;
  // never silent: a missing contract once hid a wrong relative path (the spec compared against nothing)
  contract = JSON.parse(readFileSync(new URL("../../../server/forge3/certs/box-contract.json", import.meta.url), "utf8"));
  const out = [];
  for (const [fam, band] of [["older", "b3"], ["young", "b2"]]) {
    for (const [id] of VIEWPORTS) {
      const c = contract?.boxes?.[band];
      const key = id === "w1280" ? null : id;
      const T = key && c?.tray?.[key]?.box, P = key && c?.play?.[key]?.box;
      const s = boxes[fam][id].stage.box, p = boxes[fam][id].play.box;
      const ge = (a, b) => !b || (a.w >= b.w && a.h >= b.h);
      const ok = ge(s, T) && ge(p, P);
      if (!ok) shrinks.push(`${fam} ${id}`);
      const f = (b) => (b ? `${b.w}×${b.h}` : "—");
      out.push(`| ${fam} | ${id} | ${f(T)} | ${f(s)} | ${f(P)} | ${f(p)} | ${ok ? "yes" : "**NO**"} |`);
    }
  }
  return out.join("\n");
})()}

${shrinks.length ? `**Shrinks: ${shrinks.join(", ")}.**` : "Every stage slot is at least as wide and tall as the tray box it replaces, and every play slot at least the play box: certified pieces only gain room."}
The "with answer" box is new (today the pad replaces the piece); Studio certifies it as a separate, smaller box.
`;

mkdirSync(OUT, { recursive: true });
if (shrinks.length) { console.error("box contract would shrink:", shrinks.join(", ")); process.exitCode = 1; }
const json = JSON.stringify({ v: 1, owner: "stream E (app)", source: "src/ui-v3/kaksha/lesson/stageLayout.ts", answerSurface: PAD, boxes }, null, 1) + "\n";
if (process.argv.includes("--check")) {
  const same = readFileSync(new URL("STAGE-GEOMETRY.md", OUT), "utf8") === md && readFileSync(new URL("stage-boxes.json", OUT), "utf8") === json;
  if (!same) { console.error("STAGE-GEOMETRY.md / stage-boxes.json are stale: run node src/child/dev/stage-geometry.mjs"); process.exit(1); }
} else {
  writeFileSync(new URL("STAGE-GEOMETRY.md", OUT), md);
  writeFileSync(new URL("stage-boxes.json", OUT), json);
  console.log("wrote docs/design/round7/app/STAGE-GEOMETRY.md and stage-boxes.json");
}
