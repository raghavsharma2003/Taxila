#!/usr/bin/env node
// The law-family backlog (r7 Games, main 2026-11-04): class 4-7 topics that ITEM-ARENA alone serves, and those with no game
// at all, from data/play/coverage.json and the curriculum. ITEM-ARENA is a last-resort net and never counts as coverage.
//   node server/play/tools/law-backlog.mjs   → docs/design/round7/games/law-backlog.md
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const cov = JSON.parse(readFileSync(join(ROOT, "data/play/coverage.json"), "utf8"));
const cur = {};
for (const f of readdirSync(join(ROOT, "data/curriculum"))) if (/^c[4-7]-(maths|science|evs)\.json$/.test(f)) {
  for (const ch of JSON.parse(readFileSync(join(ROOT, "data/curriculum", f), "utf8")).chapters ?? []) for (const t of ch.topics ?? []) cur[t.id] = t.title;
}
const law = new Set(cov.entries.filter((e) => e.family !== "arena").map((e) => e.topicId));
const arena = new Set(cov.arenaOnly ?? []);
let out = "# Games law-family backlog (classes 4-7)\n\nGenerated by `node server/play/tools/law-backlog.mjs` from `data/play/coverage.json` (r7 Games, main decision 2026-11-04). ITEM-ARENA is a last-resort net, so a topic it alone serves still needs a law family (a real mechanic). Regenerate after every coverage change.\n\n";
for (const subj of ["maths", "science", "evs"]) {
  const ids = Object.keys(cur).filter((id) => id.includes(`-${subj}-`)).sort();
  const a = ids.filter((id) => arena.has(id)), none = ids.filter((id) => !law.has(id) && !arena.has(id));
  out += `## ${subj}: ${ids.filter((i) => law.has(i)).length} of ${ids.length} topics have a law game\n\n### ITEM-ARENA only (${a.length})\n\n${a.map((id) => `- ${id}: ${cur[id]}`).join("\n")}\n\n### No game at all (${none.length})\n\n${none.map((id) => `- ${id}: ${cur[id]}`).join("\n")}\n\n`;
}
writeFileSync(join(ROOT, "docs/design/round7/games/law-backlog.md"), out);
console.log("wrote docs/design/round7/games/law-backlog.md");
